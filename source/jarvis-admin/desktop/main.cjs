app.whenReady().then(() => {
  // Electron performs a permission check before (and, depending on Chromium
  // version, sometimes without) issuing the permission request callback. Both
  // gates must allow the trusted local dashboard or getUserMedia fails with a
  // generic NotAllowedError even though Windows microphone privacy is enabled.
  session.defaultSession.setPermissionCheckHandler((webContents, permission, requestingOrigin) => {
    const origin = requestingOrigin || webContents?.getURL() || ''
    return permission === 'media' && trustedUrl(origin)
  })
  session.defaultSession.setPermissionRequestHandler((webContents, permission, callback, details) => {
    const origin = details?.requestingUrl || webContents.getURL()
    callback(permission === 'media' && trustedUrl(origin))
  })

  ipcMain.handle('jarvis:system-snapshot', async (event) => {
    if (!trustedSender(event)) throw new Error('Untrusted renderer')
    const [cpuUsagePercent, gpu] = await Promise.all([sampleCpuPercent(), sampleNvidiaGpu()])
    return {
      hostname: os.hostname(),
      platform: `${os.type()} ${os.release()}`,
      uptimeSeconds: Math.floor(os.uptime()),
      totalMemoryGb: Math.round(os.totalmem() / 1024 ** 2) / 1024,
      freeMemoryGb: Math.round(os.freemem() / 1024 ** 2) / 1024,
      cpuCount: os.cpus().length,
      cpuUsagePercent,
      gpu,
      desktop: true,
    }
  })

  ipcMain.handle('jarvis:screen-context', async (event) => {
    if (!trustedSender(event)) throw new Error('Untrusted renderer')
    return inspectDesktopContext()
  })

  ipcMain.handle('jarvis:desktop-action', async (event, action) => {
    if (!trustedSender(event)) throw new Error('Untrusted renderer')
    if (!action || typeof action.type !== 'string') {
      throw new Error('Invalid desktop action')
    }

    if (INPUT_ACTIONS.has(action.type)) {
      const result = await runInputAction(action)
      const delivered = result.success === true
      if (delivered) recordAction(`input_${action.type}`, String(result.evidence?.matched ?? action.target ?? action.type), { deliveryVerified: true })
      return {
        success: delivered,
        message: delivered ? `${result.message} Windows verified delivery of the input event.` : (result.message || 'Windows rejected the input event.'),
        evidence: { ...(result.evidence || {}), verified: delivered, verification: 'windows_input_delivery' },
      }
    }

    if (action.type === 'process_snapshot') {
      const result = await runDesktopScript('windows-control.ps1', ['-Action', 'process_snapshot'], 8_000)
      const processes = Array.isArray(result.processes) ? result.processes : []
      const summary = processes.slice(0, 5).map((item, index) => `${index + 1}. ${item.name} (${item.memoryMb} MB)`).join('; ')
      return { success: result.success === true, message: summary ? `Highest current memory consumers: ${summary}.` : 'No process snapshot was available.', evidence: { verified: result.verified === true, count: processes.length } }
    }

    if (action.type === 'action_history') {
      const recent = actionReceipts.slice(-10).reverse()
      const summary = recent.map((item) => `${item.operation.replaceAll('_', ' ')}: ${item.target}`).join('; ')
      return { success: true, message: summary ? `In this session I verified these actions: ${summary}.` : 'I have not made any verified PC changes in this session.', evidence: { verified: true, count: recent.length } }
    }

    if (action.type === 'file_search') {
      const values = action.arguments && typeof action.arguments === 'object' ? action.arguments : {}
      const matches = searchApprovedFiles(values)
      const first = matches[0]
      return {
        success: true,
        message: first ? `Found ${matches.length} matching file${matches.length === 1 ? '' : 's'}. Newest: ${first.name}.` : 'No matching files were found in the approved folder.',
        evidence: { verified: true, count: matches.length, ...(first ? { path: first.path, name: first.name, modifiedAt: first.modifiedAt } : {}) },
      }
    }

    if (action.type === 'open_file') {
      const values = action.arguments && typeof action.arguments === 'object' ? action.arguments : {}
      const resolved = canonicalApprovedFile(String(values.path ?? action.target ?? ''))
      const error = await shell.openPath(resolved)
      if (error) throw new Error(error)
      recordAction('open_file', resolved)
      return { success: true, message: `Opened ${path.basename(resolved)}.`, evidence: { verified: true, path: resolved } }
    }

    if (action.type === 'window_control') {
      const values = action.arguments && typeof action.arguments === 'object' ? action.arguments : {}
      const query = String(values.query ?? action.target ?? '').trim()
      const operation = String(values.operation ?? '')
      const allowedOperations = new Set(['focus', 'minimize', 'maximize', 'restore', 'snap_left', 'snap_right', 'move_monitor'])
      if (!query || query.length > 120 || !allowedOperations.has(operation)) throw new Error('A valid named window operation is required.')
      const args = ['-Action', 'window_control', '-Query', query, '-Operation', operation]
      if (operation === 'move_monitor') {
        const monitor = Number(values.monitor)
        if (!Number.isInteger(monitor) || monitor < 1 || monitor > 16) throw new Error('A valid monitor number is required.')
        args.push('-Monitor', String(monitor))
      }
      const result = await runDesktopScript('windows-control.ps1', args, 10_000)
      if (result.success === true && result.verified === true) recordAction(`window_${operation}`, String(result.target ?? query), { processId: Number(result.processId ?? 0) })
      return {
        success: result.success === true && result.verified === true,
        message: result.success === true && result.verified === true ? `${operation.replaceAll('_', ' ')} completed for ${result.target} and verified.` : `The ${operation.replaceAll('_', ' ')} operation could not be verified.`,
        evidence: { process: String(result.target ?? ''), processId: Number(result.processId ?? 0), verified: result.verified === true, monitorCount: Number(result.monitorCount ?? 0) },
      }
    }

    if (action.type === 'open_app' && typeof action.target === 'string' && Object.hasOwn(APP_COMMANDS, action.target)) {
      const focusTarget = action.target === 'browser' ? 'browser' : action.target
      try {
        const focused = await runDesktopScript('windows-control.ps1', ['-Action', 'window_control', '-Query', focusTarget, '-Operation', 'focus'], 4_000)
        if (focused.success === true && focused.verified === true) {
          recordAction('focus_application', action.target)
          return { success: true, message: `Focused the existing ${action.target.replaceAll('_', ' ')} window and verified it.`, evidence: { process: String(focused.target ?? ''), verified: true } }
        }
      } catch { /* no existing visible window; launch one below */ }
      const [executable, ...args] = APP_COMMANDS[action.target]
      runDetached(executable, args)
      await new Promise((resolve) => setTimeout(resolve, 650))
      const processNames = APP_PROCESS_NAMES[action.target] || [path.basename(executable)]
      const verified = await processIsRunning(processNames)
      if (verified) recordAction('open_application', action.target)
      return verified
        ? { success: true, message: `Opened ${action.target.replaceAll('_', ' ')} and verified its process.`, evidence: { process: processNames[0], verified: true } }
        : { success: false, message: `Windows accepted the ${action.target.replaceAll('_', ' ')} launch request, but JARVIS could not verify the process.`, evidence: { process: processNames[0], verified: false } }
    }
    if (action.type === 'open_folder' && typeof action.target === 'string' && Object.hasOwn(FOLDERS, action.target)) {
      const error = await shell.openPath(FOLDERS[action.target])
      if (error) throw new Error(error)
      await new Promise((resolve) => setTimeout(resolve, 650))
      let verified = false
      let processName = ''
      try {
        const result = await runDesktopScript('windows-control.ps1', ['-Action', 'window_control', '-Query', action.target, '-Operation', 'focus'], 5_000)
        verified = result.success === true && result.verified === true
        processName = String(result.target ?? '')
      } catch { /* Explorer accepted the path, but no matching window was observable. */ }
      if (verified) recordAction('open_folder', FOLDERS[action.target])
      return verified
        ? { success: true, message: `Opened the ${action.target} folder and verified its Explorer window.`, evidence: { verified: true, path: FOLDERS[action.target], process: processName } }
        : { success: true, message: `Windows accepted the ${action.target} folder request, but JARVIS could not verify the Explorer window.`, evidence: { verified: false, accepted: true, path: FOLDERS[action.target] } }
    }
    if (action.type === 'open_settings' && action.target === 'windows') {
      await shell.openExternal('ms-settings:')
      await new Promise((resolve) => setTimeout(resolve, 650))
      let verified = false
      try {
        const result = await runDesktopScript('windows-control.ps1', ['-Action', 'window_control', '-Query', 'Settings', '-Operation', 'focus'], 5_000)
        verified = result.success === true && result.verified === true
      } catch { /* Windows accepted the URI, but no Settings window was observable. */ }
      if (verified) recordAction('open_settings', 'windows')
      return verified
        ? { success: true, message: 'Opened Windows Settings and verified its window.', evidence: { verified: true } }
        : { success: true, message: 'Windows accepted the Settings request, but JARVIS could not verify its window.', evidence: { verified: false, accepted: true } }
    }
    if (action.type === 'system_action' && typeof action.target === 'string') {
      if (action.target === 'lock') runDetached('rundll32.exe', ['user32.dll,LockWorkStation'])
      else if (action.target === 'volume_mute') runDetached('powershell.exe', ['-NoProfile', '-WindowStyle', 'Hidden', '-Command', '(New-Object -ComObject WScript.Shell).SendKeys([char]173)'])
      else if (action.target === 'volume_up') runDetached('powershell.exe', ['-NoProfile', '-WindowStyle', 'Hidden', '-Command', '(New-Object -ComObject WScript.Shell).SendKeys([char]175)'])
      else if (action.target === 'volume_down') runDetached('powershell.exe', ['-NoProfile', '-WindowStyle', 'Hidden', '-Command', '(New-Object -ComObject WScript.Shell).SendKeys([char]174)'])
      else if (action.target === 'sleep') runDetached('rundll32.exe', ['powrprof.dll,SetSuspendState', '0,1,0'])
      else if (action.target === 'shutdown_pc') runDetached('shutdown.exe', ['/s', '/t', '5', '/c', 'JARVIS operator-approved shutdown'])
      else if (action.target === 'restart_pc') runDetached('shutdown.exe', ['/r', '/t', '5', '/c', 'JARVIS operator-approved restart'])
      else throw new Error('That system action is not in the local safety allowlist.')
      return {
        success: true,
        message: `Windows accepted the ${action.target.replaceAll('_', ' ')} request; completion cannot be verified before the system state changes.`,
        evidence: { verified: false, accepted: true, request: action.target },
      }
    }
    throw new Error('That desktop action is not in the local safety allowlist.')
  })

  ipcMain.handle('jarvis:window', (event, action) => {
    if (!trustedSender(event) || !mainWindow) return false
    if (action === 'minimize') {
      if (minimizeDisposition({ authenticated: dashboardAuthenticated, currentMode: currentWindowMode }) === 'overlay') enterOverlay()
      else mainWindow.minimize()
    }
    else if (action === 'toggle-maximize') mainWindow.isMaximized() ? mainWindow.unmaximize() : mainWindow.maximize()
    else if (action === 'close') mainWindow.hide()
    else return false
    return true
  })

  ipcMain.handle('jarvis:window-mode', (event, mode) => {
    if (!trustedSender(event)) return false
    if (mode === 'full') enterFullDeck()
    else if (mode === 'overlay') enterOverlay({ focus: true })
    else if (mode === 'hide') mainWindow?.hide()
    else return false
    return true
  })

  ipcMain.handle('jarvis:dashboard-ready', (event) => {
    if (!trustedSender(event)) return false
    dashboardAuthenticated = true
    schedulePresentationCollapse()
    return true
  })

  createWindow()
  createTray()
  globalShortcut.register('CommandOrControl+Space', () => {
    if (!mainWindow) return
    if (!mainWindow.isVisible()) enterOverlay({ focus: true })
    else if (currentWindowMode === 'overlay') enterFullDeck()
    else enterOverlay({ focus: true })
  })

  powerMonitor.on('resume', presentAfterWake)
  powerMonitor.on('unlock-screen', presentAfterWake)
})

app.on('window-all-closed', () => {})
app.on('before-quit', () => { quitting = true; clearCollapseTimer(); saveOverlayBounds() })
app.on('will-quit', () => globalShortcut.unregisterAll())
