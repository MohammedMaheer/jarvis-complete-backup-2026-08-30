function recordAction(operation, target, details = {}) {
  actionReceipts.push({ timestamp: new Date().toISOString(), operation, target: String(target).slice(0, 240), details })
  if (actionReceipts.length > 100) actionReceipts.splice(0, actionReceipts.length - 100)
}

const INPUT_ACTIONS = new Set(['cursor_move', 'cursor_click', 'click_element', 'type_text', 'key_press'])
