function trustedUrl(value) {
  try {
    return TRUSTED_ORIGINS.has(new URL(value).origin)
  } catch {
    return false
  }
}

function trustedSender(event) {
  return trustedUrl(event.senderFrame.url)
}

function overlayStatePath() {
  return path.join(app.getPath('userData'), 'overlay-state.json')
}

function readOverlayBounds() {
  try {
    const parsed = JSON.parse(readFileSync(overlayStatePath(), 'utf8'))
    if ([parsed.x, parsed.y, parsed.width, parsed.height].every(Number.isFinite)) return parsed
  } catch { /* first launch or invalid local state */ }
  return null
}

function saveOverlayBounds() {
  if (!mainWindow || mainWindow.isDestroyed() || currentWindowMode !== 'overlay') return
  const bounds = mainWindow.getBounds()
  try { writeFileSync(overlayStatePath(), JSON.stringify(bounds), 'utf8') } catch { /* position persistence is best effort */ }
}

function appRoute(route) {
  return new URL(route, `${JARVIS_URL.replace(/\/$/, '')}/`).toString()
}

function clearCollapseTimer() {
  if (collapseTimer) clearTimeout(collapseTimer)
  collapseTimer = null
}

function defaultOverlayBounds() {
  const display = screen.getDisplayNearestPoint(screen.getCursorScreenPoint())
  const area = display.workArea
  const width = Math.min(OVERLAY_WIDTH, area.width - 32)
  const height = Math.min(OVERLAY_HEIGHT, area.height - 32)
  return { x: area.x + area.width - width - 18, y: area.y + area.height - height - 18, width, height }
}

function enterOverlay({ focus = false } = {}) {
  if (!mainWindow || mainWindow.isDestroyed()) return
  // Never squeeze authentication into the compact surface. The renderer marks
  // the dashboard ready only after the protected command deck has mounted.
  if (!dashboardAuthenticated) {
    enterFullDeck({ presentation: presentationPending })
    return
  }
  clearCollapseTimer()
  currentWindowMode = 'overlay'
  if (mainWindow.isFullScreen()) mainWindow.setFullScreen(false)
  if (mainWindow.isMaximized()) mainWindow.unmaximize()
  mainWindow.setAlwaysOnTop(true, 'floating')
  mainWindow.setSkipTaskbar(false)
  mainWindow.setMinimumSize(360, 480)
  const saved = readOverlayBounds()
  const target = saved || defaultOverlayBounds()
  const display = screen.getDisplayMatching(target)
  const area = display.workArea
  const width = Math.max(360, Math.min(target.width, area.width - 24))
  const height = Math.max(480, Math.min(target.height, area.height - 24))
  const x = Math.max(area.x + 12, Math.min(target.x, area.x + area.width - width - 12))
  const y = Math.max(area.y + 12, Math.min(target.y, area.y + area.height - height - 12))
  mainWindow.setBounds({ x, y, width, height })
  const reveal = () => focus ? (mainWindow.show(), mainWindow.focus()) : mainWindow.showInactive()
  if (!mainWindow.webContents.getURL().includes('/overlay')) {
    mainWindow.webContents.once('did-finish-load', reveal)
    void mainWindow.loadURL(appRoute('/overlay'))
  } else reveal()
}

function enterFullDeck({ presentation = false } = {}) {
  if (!mainWindow || mainWindow.isDestroyed()) return
  saveOverlayBounds()
  clearCollapseTimer()
  currentWindowMode = 'full'
  presentationPending = presentation
  mainWindow.setAlwaysOnTop(false)
  mainWindow.setMinimumSize(960, 680)
  const reveal = () => {
    mainWindow.maximize()
    mainWindow.show()
    mainWindow.focus()
  }
  if (!mainWindow.webContents.getURL().includes('/dashboard')) {
    mainWindow.webContents.once('did-finish-load', reveal)
    void mainWindow.loadURL(appRoute('/dashboard'))
  } else reveal()
}

function schedulePresentationCollapse() {
  if (!presentationPending || currentWindowMode !== 'full') return
  presentationPending = false
  clearCollapseTimer()
  collapseTimer = setTimeout(() => enterOverlay(), STARTUP_PRESENTATION_MS)
}

function presentAfterWake() {
  const now = Date.now()
  // Windows commonly emits resume and unlock-screen for the same wake cycle.
  if (now - lastWakePresentationAt < 3_000) return
  lastWakePresentationAt = now
  enterFullDeck({ presentation: true })
}

function runDetached(executable, args = []) {
  const child = spawn(executable, args, { detached: true, stdio: 'ignore', windowsHide: true })
  child.unref()
}

function processIsRunning(imageNames, timeoutMs = 2_500) {
  const expected = imageNames.map((value) => value.toLowerCase())
  return new Promise((resolve) => {
    const child = spawn('tasklist.exe', ['/FO', 'CSV', '/NH'], { stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true })
    let output = ''
    let settled = false
    const finish = (value) => {
      if (settled) return
      settled = true
      clearTimeout(timer)
      resolve(value)
    }
    const timer = setTimeout(() => { child.kill(); finish(false) }, timeoutMs)
    child.stdout.setEncoding('utf8')
    child.stdout.on('data', (chunk) => { if (output.length < 1_000_000) output += chunk })
    child.once('error', () => finish(false))
    child.once('close', (code) => {
      const haystack = output.toLowerCase()
      finish(code === 0 && expected.some((name) => haystack.includes(`"${name}"`)))
    })
  })
}

function canonicalApprovedFile(filePath) {
  const resolved = realpathSync(path.resolve(filePath))
  const allowed = Object.values(FOLDERS).map((folder) => realpathSync(folder).toLowerCase())
  const normalized = resolved.toLowerCase()
  if (!allowed.some((root) => normalized === root || normalized.startsWith(`${root}${path.sep}`))) throw new Error('That file is outside the approved local folders.')
  if (!statSync(resolved).isFile()) throw new Error('The resolved target is not a file.')
  return resolved
}

function searchApprovedFiles({ scope = 'downloads', query = '', extension = '' } = {}) {
  if (!Object.hasOwn(FOLDERS, scope)) throw new Error('That search location is not approved.')
  const root = realpathSync(FOLDERS[scope])
  const needle = String(query).trim().toLowerCase()
  const suffix = String(extension).trim().toLowerCase().replace(/^\./, '')
  const results = []
  const pending = [{ directory: root, depth: 0 }]
  let inspected = 0
  while (pending.length && inspected < 4_000 && results.length < 20) {
    const current = pending.shift()
    let entries = []
    try { entries = readdirSync(current.directory, { withFileTypes: true }) } catch { continue }
    for (const entry of entries) {
      if (inspected++ >= 4_000) break
      const candidate = path.join(current.directory, entry.name)
      let metadata
      try {
        const link = lstatSync(candidate)
        if (link.isSymbolicLink()) continue
        metadata = statSync(candidate)
      } catch { continue }
      if (entry.isDirectory()) {
        if (current.depth < 3 && !entry.name.startsWith('.')) pending.push({ directory: candidate, depth: current.depth + 1 })
        continue
      }
      if (!entry.isFile()) continue
      const name = entry.name.toLowerCase()
      if (needle && !name.includes(needle)) continue
      if (suffix && path.extname(name).slice(1) !== suffix) continue
      results.push({ name: entry.name, path: candidate, modifiedAt: metadata.mtime.toISOString(), sizeBytes: metadata.size })
    }
  }
  return results.sort((left, right) => right.modifiedAt.localeCompare(left.modifiedAt)).slice(0, 10)
}

function cpuTimes() {
  return os.cpus().reduce((totals, cpu) => {
    totals.idle += cpu.times.idle
    totals.total += Object.values(cpu.times).reduce((sum, value) => sum + value, 0)
    return totals
  }, { idle: 0, total: 0 })
}

async function sampleCpuPercent() {
  const before = cpuTimes()
  await new Promise((resolve) => setTimeout(resolve, 180))
  const after = cpuTimes()
  const total = Math.max(1, after.total - before.total)
  return Math.max(0, Math.min(100, Math.round((1 - (after.idle - before.idle) / total) * 100)))
}

function sampleNvidiaGpu() {
  if (Date.now() - gpuSnapshotCache.capturedAt < 5_000) return Promise.resolve(gpuSnapshotCache.value)
  return new Promise((resolve) => {
    const child = spawn('nvidia-smi.exe', ['--query-gpu=name,utilization.gpu,memory.used,memory.total,temperature.gpu', '--format=csv,noheader,nounits'], { stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true })
    let output = ''
    const timer = setTimeout(() => { child.kill(); resolve(null) }, 2_500)
    child.stdout.setEncoding('utf8')
    child.stdout.on('data', (chunk) => { if (output.length < 2_048) output += chunk })
    child.once('error', () => { clearTimeout(timer); resolve(null) })
    child.once('close', (code) => {
      clearTimeout(timer)
      if (code !== 0) { resolve(null); return }
      const [name, utilization, memoryUsed, memoryTotal, temperature] = output.trim().split(',').map((value) => value.trim())
      if (!name || !Number.isFinite(Number(memoryTotal))) { resolve(null); return }
      const value = { name, utilizationPercent: Number(utilization), memoryUsedMb: Number(memoryUsed), memoryTotalMb: Number(memoryTotal), temperatureC: Number(temperature) }
      gpuSnapshotCache = { capturedAt: Date.now(), value }
      resolve(value)
    })
  })
}

function desktopScriptPath(scriptName) {
  if (app.isPackaged) return path.join(process.resourcesPath, 'app.asar.unpacked', 'desktop', scriptName)
  return path.join(__dirname, scriptName)
}

function runDesktopScript(scriptName, args = [], timeoutMs = 8_000) {
  return new Promise((resolve, reject) => {
    const child = spawn('powershell.exe', [
      '-NoLogo', '-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass',
      '-File', desktopScriptPath(scriptName), ...args,
    ], { stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true })
    const stdoutChunks = []
    let stdoutBytes = 0
    let stderr = ''
    let settled = false
    const finish = (callback) => {
      if (settled) return
      settled = true
      clearTimeout(timer)
      callback()
    }
    const timer = setTimeout(() => {
      child.kill()
      finish(() => reject(new Error('The bounded desktop action timed out.')))
    }, timeoutMs)
    child.stderr.setEncoding('utf8')
    child.stdout.on('data', (chunk) => {
      stdoutChunks.push(Buffer.from(chunk))
      stdoutBytes += chunk.length
      if (stdoutBytes > 1_000_000) child.kill()
    })
    child.stderr.on('data', (chunk) => { stderr += chunk })
    child.on('error', (error) => finish(() => reject(error)))
    child.on('close', (code) => finish(() => {
      if (code !== 0) {
        reject(new Error((stderr || 'The desktop action failed.').trim().slice(0, 500)))
        return
      }
      try {
        resolve(parsePowerShellJson(stdoutChunks))
      } catch {
        reject(new Error('The desktop action returned an invalid local response.'))
      }
    }))
  })
}

function hideForUnderlyingApp() {
  const shouldRestore = Boolean(mainWindow && !mainWindow.isDestroyed() && mainWindow.isVisible())
  if (shouldRestore) mainWindow.hide()
  return async () => {
    if (!shouldRestore || !mainWindow || mainWindow.isDestroyed()) return
    await new Promise((resolve) => setTimeout(resolve, 80))
    mainWindow.showInactive()
  }
}

async function inspectDesktopContext() {
  const restore = hideForUnderlyingApp()
  try {
    await new Promise((resolve) => setTimeout(resolve, 180))
    return await runDesktopScript('windows-context.ps1', ['-MaxElements', '160'], 7_000)
  } finally {
    await restore()
  }
}

function integerCoordinate(value, label) {
  if (!Number.isInteger(value) || value < -20_000 || value > 20_000) throw new Error(`${label} must be a valid desktop coordinate.`)
  return String(value)
}

async function runInputAction(action) {
  const type = String(action.type ?? '')
  if (!INPUT_ACTIONS.has(type)) throw new Error('That input action is not allowlisted.')
  const values = action.arguments && typeof action.arguments === 'object' ? action.arguments : {}
  const args = ['-Action', type]
  if (type === 'cursor_move' || type === 'cursor_click') {
    args.push('-X', integerCoordinate(values.x, 'X'), '-Y', integerCoordinate(values.y, 'Y'))
  }
  if (type === 'cursor_click') {
    const button = values.button === 'right' ? 'right' : 'left'
    const clicks = values.clicks === 2 ? 2 : 1
    args.push('-Button', button, '-Clicks', String(clicks))
  }
  if (type === 'click_element') {
    const query = String(values.query ?? action.target ?? '').trim()
    if (!query || query.length > 120) throw new Error('An accessible element name between 1 and 120 characters is required.')
    args.push('-Query', query)
  }
  if (type === 'type_text') {
    const text = String(values.text ?? '')
    if (!text || text.length > 500 || /[\u0000-\u0008\u000B\u000C\u000E-\u001F]/.test(text)) throw new Error('Typed text must contain 1-500 safe characters.')
    args.push('-Text', text)
  }
  if (type === 'key_press') {
    const key = String(values.key ?? action.target ?? '').trim().toUpperCase()
    if (!ALLOWED_KEYS.has(key)) throw new Error('That key is outside the local key allowlist.')
    args.push('-Key', key)
  }
  const restore = hideForUnderlyingApp()
  try {
    await new Promise((resolve) => setTimeout(resolve, 180))
    return await runDesktopScript('windows-input.ps1', args, 8_000)
  } finally {
    await restore()
  }
}

function createWindow() {
  mainWindow = new BrowserWindow({
    width: 1560,
    height: 980,
    minWidth: 960,
    minHeight: 680,
    show: false,
    frame: false,
    backgroundColor: '#02070d',
    title: 'J.A.R.V.I.S. Neural Operating Interface',
    autoHideMenuBar: true,
    webPreferences: {
      preload: path.join(__dirname, 'preload.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
      webSecurity: true,
    },
  })

  mainWindow.once('ready-to-show', () => {
    mainWindow.show()
    mainWindow.maximize()
  })

  mainWindow.on('close', (event) => {
    if (quitting) return
    event.preventDefault()
    mainWindow.hide()
  })
  mainWindow.on('minimize', (event) => {
    if (minimizeDisposition({ authenticated: dashboardAuthenticated, currentMode: currentWindowMode }) !== 'overlay') return
    event.preventDefault()
    enterOverlay()
  })
  mainWindow.on('move', saveOverlayBounds)
  mainWindow.on('resize', saveOverlayBounds)

  mainWindow.webContents.setWindowOpenHandler(({ url }) => {
    if (url.startsWith('https://')) void shell.openExternal(url)
    return { action: 'deny' }
  })
  mainWindow.webContents.on('will-navigate', (event, url) => {
    try {
      if (!TRUSTED_ORIGINS.has(new URL(url).origin)) event.preventDefault()
    } catch {
      event.preventDefault()
    }
  })

  void mainWindow.loadURL(JARVIS_URL)
}

function showMainWindow() {
  if (!mainWindow || mainWindow.isDestroyed()) createWindow()
  enterFullDeck()
}

function createTray() {
  if (tray) return
  const iconPath = path.join(__dirname, 'jarvis-icon.png')
  const icon = nativeImage.createFromPath(iconPath).resize({ width: 20, height: 20 })
  tray = new Tray(icon)
  tray.setToolTip('J.A.R.V.I.S. Neural Interface')
  tray.setContextMenu(Menu.buildFromTemplate([
    { label: 'Open full command deck', click: showMainWindow },
    { label: 'Show compact overlay', click: () => enterOverlay({ focus: true }) },
    { label: 'Hide interface', click: () => mainWindow?.hide() },
    { type: 'separator' },
    { label: 'Quit desktop interface', click: () => { quitting = true; app.quit() } },
  ]))
  tray.on('click', showMainWindow)
}

